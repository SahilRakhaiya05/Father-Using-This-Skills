def cmd_render(a):
    ffmpeg = need("ffmpeg")
    out = Path(a.out)
    ext = out.suffix.lower()
    if ext not in (".mp4", ".webm", ".mov", ".gif"):
        die("output must end in .mp4, .webm, .mov or .gif")
    if a.alpha and ext not in (".webm", ".mov"):
        die("--alpha needs .webm (VP9 with alpha) or .mov (ProRes 4444)")
    issues, _, _ = lint_project(Path(a.dir))
    errs = [m for lv, m in issues if lv == "error"]
    if errs and not a.no_lint:
        for m in errs:
            print("ERROR  " + m)
        die("lint errors - fix them (or pass --no-lint if you are sure)", 1)
    st = Stage(a.dir, scale=a.scale, alpha=a.alpha)
    try:
        fps = st.fps
        t0, t1 = 0.0, st.duration
        if a.range:
            m = re.fullmatch(r"\s*([\d.]+)\s*-\s*([\d.]+)\s*", a.range)
            if not m:
                die("--range looks like 2-5.5 (seconds)")
            t0, t1 = float(m.group(1)), min(float(m.group(2)), st.duration)
        f0, f1 = round(t0 * fps), round(t1 * fps)
        n = f1 - f0
        if n <= 0:
            die("nothing to render in that range")
        vf = "scale=trunc(iw/2)*2:trunc(ih/2)*2:flags=lanczos"
        cmd = [ffmpeg, "-y", "-loglevel", "error", "-f", "image2pipe", "-framerate", str(fps),
               "-c:v", "png" if a.alpha else "mjpeg", "-i", "-"]
        audio = bool(a.audio) and ext != ".gif"
        if audio:
            if not Path(a.audio).exists():
                die(f"audio file {a.audio} not found")
            cmd += ["-i", a.audio]
        dur = n / fps
        if ext == ".gif":
            cmd += ["-vf", f"fps={min(fps, 20)},split[a][b];[a]palettegen=stats_mode=diff[p];[b][p]paletteuse=dither=bayer:bayer_scale=4", "-loop", "0"]
        elif ext == ".webm":
            cmd += ["-vf", vf, "-c:v", "libvpx-vp9", "-crf", str(a.crf + 12), "-b:v", "0", "-pix_fmt", "yuva420p" if a.alpha else "yuv420p"]
        elif a.alpha:
            cmd += ["-vf", vf, "-c:v", "prores_ks", "-profile:v", "4444", "-pix_fmt", "yuva444p10le"]
        else:
            cmd += ["-vf", vf + ",format=yuv420p", "-c:v", "libx264", "-preset", a.preset, "-crf", str(a.crf),
                    "-pix_fmt", "yuv420p", "-color_primaries", "bt709", "-color_trc", "bt709", "-colorspace", "bt709",
                    "-movflags", "+faststart"]
        if audio:
            fade = min(0.6, dur / 4)
            cmd += ["-af", f"volume={a.audio_volume},afade=t=out:st={max(0, dur - fade):.3f}:d={fade:.3f}",
                    "-c:a", "libopus" if ext == ".webm" else "aac", "-b:a", "192k", "-map", "0:v", "-map", "1:a", "-t", f"{dur:.4f}"]
        part = out.with_name(out.stem + ".part" + ext)
        out.parent.mkdir(parents=True, exist_ok=True)
        cmd += ["-r", str(fps) if ext != ".gif" else str(min(fps, 20)), str(part)]
        import time
        started = time.time()
        proc = subprocess.Popen(cmd, stdin=subprocess.PIPE, stderr=subprocess.PIPE)
        try:
            for i in range(n):
                proc.stdin.write(st.shot((f0 + i) / fps, a.quality))
                if not a.quiet and (i % max(1, n // 10) == 0):
                    print(f"  frame {i + 1}/{n}", flush=True)
            proc.stdin.close()
        except (BrokenPipeError, OSError):
            pass
        err = proc.stderr.read().decode("utf-8", "replace")
        if proc.wait() != 0:
            part.unlink(missing_ok=True)
            die("ffmpeg failed: " + err[-600:], 1)
        if out.exists():
            out.unlink()
        part.rename(out)
        page_errors = list(dict.fromkeys(st.errors))
    finally:
        st.close()
    secs = time.time() - started
    print(f"rendered {out} - {n} frames, {dur:.2f} s, {round(st.w * a.scale)}x{round(st.h * a.scale)} @ {fps} fps in {secs:.1f} s"
          + (" (draft scale)" if a.scale != 1 else ""))
    for e in page_errors:
        print("page error  " + e[:200])
    if page_errors:
        sys.exit(1)


# ------------------------------------------------------------------ check
def probe(path):
    r = subprocess.run([need("ffprobe"), "-v", "error", "-show_format", "-show_streams", "-of", "json", str(path)],
                       capture_output=True, text=True)
    if r.returncode != 0:
        die(f"ffprobe cannot read {path}: {r.stderr.strip()[-200:]}", 1)
    return json.loads(r.stdout)


def cmd_check(a):
    path = Path(a.file)
    if not path.exists():
        die(f"{path} not found", 1)
    info = probe(path)
    v = next((s for s in info["streams"] if s["codec_type"] == "video"), None)
    au = next((s for s in info["streams"] if s["codec_type"] == "audio"), None)
    if not v:
        die("no video stream", 1)
    num, den = (v.get("avg_frame_rate") or "0/1").split("/")
    fps = float(num) / float(den or 1) if float(den or 1) else 0
    dur = float(info["format"].get("duration") or v.get("duration") or 0)
    fails, warns = [], []
    print(f"{path.name}: {v['width']}x{v['height']}, {fps:.3f} fps, {dur:.2f} s, {v['codec_name']}/{v.get('pix_fmt')}, "
          f"audio {au['codec_name'] if au else 'none'}, {path.stat().st_size / 1e6:.2f} MB")
    ext = path.suffix.lower()
    if ext == ".mp4":
        if v["width"] % 2 or v["height"] % 2:
            fails.append("odd width/height - many players refuse it")
        if v.get("pix_fmt") != "yuv420p":
            fails.append(f"pixel format {v.get('pix_fmt')} - phones and browsers need yuv420p")
        if v["codec_name"] != "h264":
            warns.append(f"codec {v['codec_name']} - H.264 plays in the most places")
    if a.project:
        st = Stage(a.project, scale=0.25)
        try:
            want, wfps, ww, wh = st.duration, st.fps, st.w, st.h
        finally:
            st.close()
        if abs(dur - want) > 2.0 / wfps + 0.05:
            fails.append(f"duration {dur:.2f} s but the project is {want:.2f} s")
        if abs(fps - wfps) > 0.01 and ext != ".gif":
            fails.append(f"{fps:.2f} fps but the project is {wfps} fps")
        if v["width"] * wh != v["height"] * ww and abs(v["width"] / v["height"] - ww / wh) > 0.01:
            fails.append(f"aspect {v['width']}x{v['height']} does not match the project {ww}x{wh}")
        elif v["width"] < ww:
            warns.append(f"{v['width']}x{v['height']} is a draft size - final should be {ww}x{wh}")
    if ext != ".gif":
        r = subprocess.run([need("ffmpeg"), "-hide_banner", "-nostats", "-i", str(path), "-vf",
                            f"freezedetect=n=0.0005:d={a.freeze},blackdetect=d=0.5:pix_th=0.02", "-an", "-f", "null", "-"],
                           capture_output=True, text=True)
        for s, d in re.findall(r"freeze_start: ([\d.]+)[\s\S]*?freeze_duration: ([\d.]+)", r.stderr):
            warns.append(f"nothing moves for {float(d):.1f} s from {float(s):.1f} s - add a small beat or shorten the hold")
        if re.search(r"freeze_start: ([\d.]+)(?![\s\S]*freeze_end)", r.stderr):
            m = re.findall(r"freeze_start: ([\d.]+)", r.stderr)[-1]
            if dur - float(m) > a.freeze and not any(f"from {float(m):.1f} s" in w for w in warns):
                warns.append(f"nothing moves from {float(m):.1f} s to the end ({dur - float(m):.1f} s)")
        for s, e in re.findall(r"black_start:([\d.]+) black_end:([\d.]+)", r.stderr):
            if not a.allow_black:
                warns.append(f"black frames {float(s):.1f}-{float(e):.1f} s")
    if au:
        r = subprocess.run([need("ffmpeg"), "-hide_banner", "-nostats", "-i", str(path), "-af", "volumedetect", "-vn", "-f", "null", "-"],
                           capture_output=True, text=True)
        m = re.search(r"max_volume: (-?[\d.]+) dB", r.stderr)
        mean = re.search(r"mean_volume: (-?[\d.]+) dB", r.stderr)
        if m and float(m.group(1)) >= -0.1:
            warns.append(f"audio peaks at {m.group(1)} dB - likely clipping, lower the volume")
        if mean and float(mean.group(1)) < -40:
            warns.append(f"audio is nearly silent (mean {mean.group(1)} dB)")
    for f in fails:
        print("FAIL  " + f)
    for w in warns:
        print("warn  " + w)
    print("OK: file is ready to deliver" if not fails and not warns else
          ("OK with warnings - read them" if not fails else f"{len(fails)} problem(s) to fix"))
    sys.exit(1 if fails else 0)


