def lint_project(d):
    issues = []
    index = d / "index.html"
    if not index.exists():
        die(f"{index} not found - create a project with `mg.py new`")
    text = index.read_text(encoding="utf-8")
    scan = _Scan()
    scan.feed(text)
    issues += scan.issues
    if 'id="stage"' not in text:
        issues.append(("error", 'no <div id="stage"> - scenes must live inside it'))
    if not re.search(r"<script[^>]+mg\.js", text):
        issues.append(("error", "mg.js is not loaded"))
    if not scan.scenes:
        issues.append(("error", 'no <section class="scene"> found'))
    total = 0.0
    for sc in scan.scenes:
        if sc["dur"] is None:
            issues.append(("warn", f"scene {sc['id']}: no data-dur, defaults to 3 s"))
        try:
            dur = float(sc["dur"] or 3)
        except ValueError:
            issues.append(("error", f"scene {sc['id']}: data-dur must be a number"))
            continue
        total += dur
        need_t = sc["last"] + 0.4 + sc["words"] * 0.16
        if sc["last"] > dur + 0.01:
            issues.append(("error", f"scene {sc['id']}: an animation ends at {sc['last']:.2f} s but the scene is only {dur:.2f} s long"))
        elif sc["words"] and dur < need_t:
            issues.append(("warn", f"scene {sc['id']}: {sc['words']} words in {dur:.1f} s is hard to read - needs about {need_t:.1f} s, or fewer words"))
        if sc["words"] > 28:
            issues.append(("warn", f"scene {sc['id']}: {sc['words']} words on one screen - split it or cut copy (aim for 12 or fewer)"))
        if dur > 8:
            issues.append(("warn", f"scene {sc['id']}: {dur:.0f} s is a long hold - add a beat or a second scene"))
    for f in sorted(d.rglob("*")):
        if f.name == "mg.js" or "node_modules" in f.parts or f.suffix not in (".html", ".js", ".mjs", ".css"):
            continue
        src = f.read_text(encoding="utf-8", errors="replace")
        rules = (CLOCKS if f.suffix != ".css" else []) + (CSS_MOTION if f.suffix in (".css", ".html") else [])
        for n, line in enumerate(src.splitlines(), 1):
            if "mg-allow" in line:
                continue
            for pat, why in rules:
                if re.search(pat, line):
                    issues.append(("error", f"{f.relative_to(d)}:{n}: {why}"))
    return issues, scan, total


def cmd_lint(a):
    issues, scan, total = lint_project(Path(a.dir))
    for level, msg in issues:
        print(f"{'ERROR' if level == 'error' else 'warn '}  {msg}")
    errs = sum(1 for lv, _ in issues if lv == "error")
    print(f"{len(scan.scenes)} scene(s), about {total:.1f} s before transition overlaps - {errs} error(s), {len(issues) - errs} warning(s)")
    sys.exit(1 if errs else 0)


# ------------------------------------------------------------------ browser
class Stage:
    def __init__(self, d, scale=1.0, alpha=False):
        try:
            from playwright.sync_api import sync_playwright
        except ImportError:
            die("playwright is not installed: pip install playwright && python -m playwright install chromium")
        index = Path(d).resolve() / "index.html"
        if not index.exists():
            die(f"{index} not found - create a project with `mg.py new`")
        self.errors = []
        self._pw = sync_playwright().start()
        try:
            self.browser = self._pw.chromium.launch(args=["--force-color-profile=srgb", "--font-render-hinting=none",
                                                          "--disable-lcd-text", "--hide-scrollbars"])
        except Exception as e:  # noqa: BLE001
            self._pw.stop()
            die(f"could not start Chromium ({str(e).splitlines()[0]}). Run: python -m playwright install chromium")
        probe = self.browser.new_page()
        probe.goto(index.as_uri() + "#render")
        probe.wait_for_function("window.__mg && window.__mg.duration !== undefined", timeout=20000)
        self.w, self.h = probe.evaluate("[__mg.width, __mg.height]")
        probe.close()
        self.page = self.browser.new_page(viewport={"width": self.w, "height": self.h}, device_scale_factor=scale)
        self.page.on("pageerror", lambda e: self.errors.append(str(e)))
        self.page.on("console", lambda m: self.errors.append(m.text) if m.type == "error" else None)
        self.page.goto(index.as_uri() + "#render")
        self.page.wait_for_function("window.__mg && window.__mg.duration !== undefined", timeout=20000)
        self.page.evaluate("() => window.__mg.ready")
        if alpha:
            self.page.evaluate("() => document.documentElement.classList.add('mg-alpha')")
        self.alpha = alpha
        self.fps = self.page.evaluate("__mg.fps")
        self.duration = self.page.evaluate("__mg.duration")
        self.scenes = self.page.evaluate("__mg.scenes")
        if self.duration <= 0:
            self.close()
            die("the project has no duration - add scenes with data-dur")

    def shot(self, t, quality=92):
        self.page.evaluate("t => window.__mg.seek(t)", t)
        if self.alpha:
            return self.page.screenshot(type="png", omit_background=True)
        return self.page.screenshot(type="jpeg", quality=quality)

    def layout(self):
        return self.page.evaluate(r"""() => {
          const W = __mg.width, H = __mg.height, out = [], boxes = [];
          const vis = [...document.querySelectorAll('.scene')].filter(s => getComputedStyle(s).visibility === 'visible');
          const top = vis[vis.length - 1];
          if (!top) return out;
          for (const el of top.querySelectorAll('h1,h2,h3,p,.item,.card,.pill,.big,.quote,.kicker,[data-anim]')) {
            const cs = getComputedStyle(el);
            if (parseFloat(cs.opacity) < 0.5 || cs.visibility === 'hidden' || el.closest('.mg-w')) continue;
            const r = el.getBoundingClientRect();
            if (!r.width || !r.height) continue;
            const name = (el.tagName.toLowerCase() + (el.className && typeof el.className === 'string' ? '.' + el.className.split(' ')[0] : '') + ' "' + (el.textContent || '').trim().slice(0, 28) + '"');
            if (r.left < -2 || r.top < -2 || r.right > W + 2 || r.bottom > H + 2) out.push('off-frame: ' + name);
            else if (el.scrollWidth > el.clientWidth + 4 && cs.overflow !== 'visible') out.push('clipped text: ' + name);
            if (el.matches('h1,h2,p,.big,.quote,.pill,.kicker')) boxes.push([r, name, el]);
          }
          for (let i = 0; i < boxes.length; i++) for (let j = i + 1; j < boxes.length; j++) {
            const [a, an, ae] = boxes[i], [b, bn, be] = boxes[j];
            if (ae.contains(be) || be.contains(ae)) continue;
            const ox = Math.min(a.right, b.right) - Math.max(a.left, b.left), oy = Math.min(a.bottom, b.bottom) - Math.max(a.top, b.top);
            if (ox > 8 && oy > 8 && ox * oy > 0.12 * Math.min(a.width * a.height, b.width * b.height)) out.push('overlap: ' + an + ' and ' + bn);
          }
          return out;
        }""")

    def close(self):
        try:
            self.browser.close()
        finally:
            self._pw.stop()


def make_sheet(tiles, out, cols=None, label_h=34):
    """tiles: list of (label, jpeg/png bytes)"""
    import io
    from PIL import Image, ImageDraw, ImageFont
    imgs = [(lab, Image.open(io.BytesIO(b)).convert("RGB")) for lab, b in tiles]
    n = len(imgs)
    w0, h0 = imgs[0][1].size
    cols = cols or (4 if w0 >= h0 else 6)
    cols = min(cols, n)
    tw = 480 if w0 >= h0 else 270
    th = round(tw * h0 / w0)
    rows = -(-n // cols)
    sheet = Image.new("RGB", (cols * (tw + 8) + 8, rows * (th + label_h + 8) + 8), (24, 24, 27))
    draw = ImageDraw.Draw(sheet)
    try:
        font = ImageFont.truetype("arial.ttf", 17)
    except OSError:
        try:
            font = ImageFont.truetype("DejaVuSans.ttf", 17)
        except OSError:
            font = ImageFont.load_default()
    for i, (lab, im) in enumerate(imgs):
        x, y = 8 + (i % cols) * (tw + 8), 8 + (i // cols) * (th + label_h + 8)
        sheet.paste(im.resize((tw, th), Image.LANCZOS), (x, y))
        draw.text((x + 2, y + th + 7), lab[:44], fill=(235, 235, 240), font=font)
    sheet.save(out)


def sample_times(stage, at):
    if at:
        return [float(x) for x in at.split(",") if x.strip()]
    early, late = [], []
    for sc in stage.scenes:
        early.append(sc["start"] + sc["transDur"] + min(sc["dur"] * 0.3, 0.45))
        late.append(sc["start"] + sc["dur"] * 0.85)
    # the settled frame of every scene matters most; add the mid-entrance frames while they fit
    times = sorted(early + late) if len(early) * 2 <= 16 else late
    step = max(1, -(-len(times) // 24))
    return [min(t, stage.duration - 1 / stage.fps) for t in times[::step]]


def cmd_sheet(a):
    st = Stage(a.dir, scale=0.5)
    try:
        tiles, report = [], []
        for t in sample_times(st, a.at):
            tiles.append((f"{t:6.2f} s", st.shot(t, 85)))
            if any(sc["start"] <= t < sc["start"] + sc["transDur"] + 0.02 for sc in st.scenes):
                continue  # mid-transition: things are meant to be off-frame
            for issue in st.layout():
                report.append(f"{t:6.2f} s  {issue}")
        make_sheet(tiles, a.out)
        errs = list(dict.fromkeys(st.errors))
    finally:
        st.close()
    print(f"wrote {a.out} - {len(tiles)} frames of {st.duration:.2f} s ({st.w}x{st.h} @ {st.fps} fps)")
    for line in dict.fromkeys(report):
        print("layout  " + line)
    for e in errs:
        print("page error  " + e[:200])
    print("look at the sheet before rendering." if not (report or errs) else f"{len(set(report))} layout issue(s), {len(errs)} page error(s) - fix, then re-run")
    sys.exit(1 if errs else 0)


