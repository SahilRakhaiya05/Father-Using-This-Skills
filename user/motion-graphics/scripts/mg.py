# ------------------------------------------------------------------ lint (static, no browser)
class _Scan(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.scenes, self.cur, self.depth, self.issues, self.body = [], None, 0, [], {}
        self.skip = 0

    def handle_starttag(self, tag, at):
        d = dict(at)
        if tag in ("script", "style"):
            self.skip += 1
        if tag == "body":
            self.body = d
        classes = (d.get("class") or "").split()
        if "scene" in classes and self.cur is None:
            self.cur = {"id": d.get("id") or f"scene{len(self.scenes) + 1}", "dur": d.get("data-dur"), "words": 0,
                        "last": 0.0, "line": self.getpos()[0]}
            self.depth = 0
            self._chk(d, "data-in", TRANSITIONS, "transition")
            self._chk(d, "data-cam", CAMS, "camera move")
        elif self.cur is not None and tag not in ("br", "img", "input", "hr", "meta", "link", "path", "circle", "rect",
                                                  "line", "polyline", "polygon", "ellipse", "source", "use", "stop"):
            self.depth += 1
        if self.cur is not None:
            self._chk(d, "data-anim", ANIMS, "animation")
            self._chk(d, "data-out", ANIMS, "exit animation")
            self._chk(d, "data-ease", EASES, "easing")
            self._chk(d, "data-loop", LOOPS, "loop")
            try:
                at_t = float(d.get("data-at") or 0) + float(d.get("data-dur") or 0.6 if "data-anim" in d else 0)
                self.cur["last"] = max(self.cur["last"], at_t)
            except ValueError:
                self.issues.append(("error", f"line {self.getpos()[0]}: data-at / data-dur must be numbers"))
        if tag == "video":
            self.issues.append(("error", f"line {self.getpos()[0]}: <video> cannot be rendered frame-exact here - "
                                         "render the graphics with --alpha and composite over footage with ffmpeg"))
        if tag == "audio":
            self.issues.append(("warn", f"line {self.getpos()[0]}: <audio> is ignored by the renderer - pass --audio to render"))
        for k in ("src", "href"):
            if re.match(r"https?://", d.get(k) or "") and tag in ("script", "link", "img"):
                self.issues.append(("warn", f"line {self.getpos()[0]}: {tag} loads {d[k][:60]} from the network - "
                                            "the render then depends on that server; copy the file into the project"))

    def _chk(self, d, key, allowed, what):
        v = d.get(key)
        if v and v not in allowed:
            self.issues.append(("error", f"line {self.getpos()[0]}: unknown {what} {v!r} - choose from {', '.join(sorted(allowed))}"))

    def handle_endtag(self, tag):
        if tag in ("script", "style"):
            self.skip = max(0, self.skip - 1)
        if self.cur is None:
            return
        if self.depth == 0 and tag == "section" or self.depth < 0:
            self.scenes.append(self.cur)
            self.cur = None
        elif tag not in ("br", "img", "input", "hr", "path", "circle", "rect", "line", "polyline", "polygon", "ellipse"):
            self.depth -= 1
            if self.depth < 0:
                self.scenes.append(self.cur)
                self.cur = None

    def handle_data(self, data):
        if self.cur is not None and not self.skip:
            self.cur["words"] += len(data.split())


