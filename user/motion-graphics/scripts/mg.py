def need(tool):
    path = shutil.which(tool)
    if not path:
        die(f"{tool} not found on PATH - install ffmpeg (it provides ffmpeg and ffprobe)")
    return path


# ------------------------------------------------------------------ styles
def load_styles():
    data = json.loads((ASSETS / "styles.json").read_text(encoding="utf-8"))
    return {s["id"]: s for s in data["styles"]}


def get_style(ref):
    styles = load_styles()
    if ref in styles:
        return dict(styles[ref])
    p = Path(ref)
    if p.suffix == ".json" and p.exists():
        custom = json.loads(p.read_text(encoding="utf-8"))
        base = dict(styles[custom.get("extends", "clean-minimal")])
        for k, v in custom.items():
            if isinstance(v, dict) and isinstance(base.get(k), dict):
                base[k] = {**base[k], **v}
            else:
                base[k] = v
        base.setdefault("id", p.stem)
        return base
    die(f"unknown style {ref!r}. Run `mg.py styles` to list them, or pass a .json style file")


