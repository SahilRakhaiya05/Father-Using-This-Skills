# ------------------------------------------------------------------ storyboard -> html
def rich(text):
    t = html.escape(str(text), quote=False)
    return re.sub(r"\*(.+?)\*", r"<em>\1</em>", t)


def attrs(**kw):
    out = []
    for k, v in kw.items():
        if k == "anim" and v == "":
            out.append(" data-anim")  # bare attribute = the style's default entrance
        elif v not in (None, ""):
            out.append(f' data-{k.replace("_", "-")}="{html.escape(str(v), quote=True)}"')
    return "".join(out)


def scene_html(sc, idx, st, vertical=False):
    kind = sc.get("type", "title")
    stag = float(st["motion"]["stagger"])
    dur_anim = float(st["motion"]["dur"])
    out, t = [], 0.15
    cls = ["scene"] + ([sc["class"]] if sc.get("class") else [])
    words = 0

    def add(tag, text, klass="", step=None, **data):
        nonlocal t, words
        k = f' class="{klass}"' if klass else ""
        data.setdefault("anim", "")
        out.append(f"    <{tag}{k}{attrs(at=round(t, 2), **data)}>{rich(text)}</{tag}>")
        words += len(str(text).split())
        t += dur_anim * 0.55 if step is None else step

    if kind in ("title", "end"):
        cls.append("center")
        if sc.get("kicker"):
            add("div", sc["kicker"], "kicker")
        n = len(str(sc.get("title", "")).split())
        add("h1" if kind == "title" else "h2", sc.get("title", ""), split="words", step=n * stag + dur_anim * 0.4)
        if sc.get("subtitle"):
            add("p", sc["subtitle"], "lead")
        if sc.get("cta"):
            add("div", sc["cta"], "pill", anim="pop")
    elif kind == "bullets":
        if sc.get("kicker"):
            add("div", sc["kicker"], "kicker")
        if sc.get("title"):
            add("h2", sc["title"], split="words", step=dur_anim * 0.9)
        out.append('    <div class="col">')
        for i, item in enumerate(sc.get("items", [])):
            words += len(str(item).split())
            out.append(f'      <div class="item"{attrs(anim="", at=round(t, 2), cue="tick")}><span class="n">{i + 1:02d}</span><span>{rich(item)}</span></div>')
            t += max(0.45, dur_anim * 0.8)
        out.append("    </div>")
    elif kind == "stat":
        cls.append("center")
        if sc.get("kicker"):
            add("div", sc["kicker"], "kicker")
        val = sc.get("value", 0)
        dec = len(str(val).split(".")[1]) if "." in str(val) else 0
        out.append(f'    <div class="big"{attrs(anim="count", at=round(t, 2), dur=sc.get("count_dur", 1.2), ease="expo", to=val, decimals=dec, prefix=sc.get("prefix", ""), suffix=sc.get("suffix", ""), cue="count")}>0</div>')
        t += 1.0
        words += 1
        if sc.get("label"):
            add("p", sc["label"], "lead")
    elif kind == "quote":
        add("div", "“" + str(sc.get("text", "")) + "”", "quote", split="words",
            step=len(str(sc.get("text", "")).split()) * stag + 0.4)
        if sc.get("by"):
            add("div", "— " + str(sc["by"]), "kicker")
    elif kind == "bars":
        if sc.get("title"):
            add("h2", sc["title"], split="words", step=dur_anim * 0.9)
        items = sc.get("items", [])
        top = max([float(i.get("value", 0)) for i in items] + [1e-9])
        out.append('    <div class="col">')
        for it in items:
            v = float(it.get("value", 0))
            dec = len(str(it.get("value")).split(".")[1]) if "." in str(it.get("value")) else 0
            words += len(str(it.get("label", "")).split()) + 1
            out.append(
                f'      <div class="barrow"><span{attrs(anim="fade", at=round(t, 2))}>{rich(it.get("label", ""))}</span>'
                f'<div class="track"><div class="fill" style="--v:{v / top * 100:.2f}%"{attrs(anim="bar", at=round(t, 2), dur=0.9, ease="expo", cue="bar")}></div></div>'
                f'<b{attrs(anim="count", at=round(t, 2), dur=0.9, ease="expo", to=it.get("value", 0), decimals=dec, suffix=sc.get("suffix", ""))}>0</b></div>')
            t += 0.25
        out.append("    </div>")
        t += 0.9
    elif kind == "cards":
        if sc.get("title"):
            add("h2", sc["title"], split="words", step=dur_anim * 0.9)
        items = sc.get("items", [])
        out.append(f'    <div class="grid" style="--cols:{sc.get("cols", 1 if vertical else min(3, max(1, len(items))))}">')
        for it in items:
            head, body = (it.get("title", ""), it.get("text", "")) if isinstance(it, dict) else (it, "")
            words += len(f"{head} {body}".split())
            out.append(f'      <div class="card"{attrs(anim="", at=round(t, 2), cue="pop")}><h3 class="accent">{rich(head)}</h3><p>{rich(body)}</p></div>')
            t += 0.3
        out.append("    </div>")
        t += dur_anim
    elif kind == "html":
        out.append("    " + str(sc.get("html", "")))
        words += len(re.sub(r"<[^>]+>", " ", str(sc.get("html", ""))).split())
    else:
        die(f"storyboard scene {idx + 1}: unknown type {kind!r} (title, bullets, stat, quote, bars, cards, end, html)")

    # hold long enough to read - the same rule `lint` checks
    body = "\n".join(out)
    last = 0.0
    for m in re.finditer(r'data-at="([0-9.]+)"(?:[^>]*?data-dur="([0-9.]+)")?', body):
        last = max(last, float(m.group(1)) + float(m.group(2) or dur_anim))
    words = len(re.sub(r"<[^>]+>", " ", body).split())
    dur = sc.get("dur") or round(max(2.2, last + 0.75 + words * 0.16), 1)
    sid = sc.get("id", f"s{idx + 1}-{kind}")
    extra = attrs(dur=dur, **{"in": sc.get("in"), "in_dur": sc.get("in_dur")})
    return f'  <section class="{" ".join(cls)}" id="{sid}"{extra}>\n' + "\n".join(out) + "\n  </section>"


