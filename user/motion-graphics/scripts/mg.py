def cmd_new(a):
    st = get_style(a.style)
    for k in ("accent", "bg", "fg"):
        if getattr(a, k):
            st["colors"] = {**st["colors"], k: getattr(a, k)}
    if a.format not in FORMATS and not re.fullmatch(r"\d+x\d+", a.format):
        die(f"unknown format {a.format!r}: use one of {', '.join(FORMATS)} or WIDTHxHEIGHT")
    w, h = FORMATS[a.format] if a.format in FORMATS else map(int, a.format.split("x"))
    if w % 2 or h % 2:
        die("width and height must be even numbers")
    story = DEMO
    if a.storyboard:
        story = json.loads(Path(a.storyboard).read_text(encoding="utf-8"))
        story = story.get("scenes", story) if isinstance(story, dict) else story
    elif a.title:
        story = [{"type": "title", "title": a.title, "subtitle": a.subtitle or ""}]
    d = Path(a.dir)
    if (d / "index.html").exists() and not a.force:
        die(f"{d / 'index.html'} already exists - pass --force to overwrite it")
    d.mkdir(parents=True, exist_ok=True)
    scenes = "\n".join(scene_html(sc, i, st, h > w * 1.2) for i, sc in enumerate(story))
    page = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>{html.escape(a.title or story[0].get('title', 'Motion graphics')).replace('*', '')}</title>
<link rel="stylesheet" href="theme.css">
</head>
<!-- Every .scene plays in order for data-dur seconds. Elements animate with data-anim / data-at (seconds
     from the start of their scene). Full attribute list: references/authoring.md in the skill. -->
<body data-fps="{a.fps}" data-width="{w}" data-height="{h}">
<div id="stage">
{scenes}
  <div id="mg-flash"></div>
</div>
<script src="mg.js"></script>
</body>
</html>
"""
    (d / "index.html").write_text(page, encoding="utf-8")
    (d / "theme.css").write_text(theme_css(st, w, h), encoding="utf-8")
    shutil.copyfile(ASSETS / "mg.js", d / "mg.js")
    print(f"created {d} - style {st['id']}, {w}x{h} @ {a.fps} fps, {len(story)} scene(s)")
    print(f"next: open {d / 'index.html'} in a browser to preview, then `mg.py sheet {d} sheet.png`")


